-- ЛР6. PostgreSQL. Виконати в базі rental_apartments (pgAdmin / psql).
-- Увага: скрипт видаляє старі таблиці з ЛР5 і створює їх заново.

DROP TABLE IF EXISTS bookings CASCADE;
DROP TABLE IF EXISTS apartments CASCADE;
DROP SEQUENCE IF EXISTS bookings_seq;

-- apartments: первинний ключ генерується autoincrement-полем (IDENTITY)
CREATE TABLE apartments (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       VARCHAR(255)     NOT NULL,
    description VARCHAR(1000),
    city        VARCHAR(100)     NOT NULL,
    rooms       INTEGER          NOT NULL CHECK (rooms > 0),
    area        DOUBLE PRECISION NOT NULL CHECK (area > 0),
    price       INTEGER          NOT NULL CHECK (price > 0)
);

-- bookings: первинний ключ генерується послідовністю (SEQUENCE)
CREATE SEQUENCE bookings_seq START WITH 1 INCREMENT BY 1;

-- Відношення один-до-багатьох: одна квартира -> багато бронювань
CREATE TABLE bookings (
    id           BIGINT PRIMARY KEY DEFAULT nextval('bookings_seq'),
    apartment_id BIGINT       NOT NULL REFERENCES apartments (id),
    client_name  VARCHAR(150) NOT NULL,
    date_from    DATE         NOT NULL,
    date_to      DATE         NOT NULL,
    status       VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'CANCELLED')),
    CONSTRAINT chk_booking_dates CHECK (date_to > date_from)
);

ALTER SEQUENCE bookings_seq OWNED BY bookings.id;
CREATE INDEX idx_bookings_apartment ON bookings (apartment_id);
